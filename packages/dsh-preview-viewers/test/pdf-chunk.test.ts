// @vitest-environment jsdom
/**
 * The pdf surface against a real document.
 *
 * The arithmetic is covered in `pdf.test.ts`; what only a mount can show is that
 * the surface actually drives pdf.js: it loads the bytes, reports the page count
 * from the document itself, and pages forward. jsdom has no canvas rasterizer and
 * no Worker, so the render call is stubbed at the context boundary and the
 * document is parsed for real, which is the part worth pinning: a stub that
 * answered a fake document would pass even if the inlining were broken.
 *
 * The fixture is built here rather than committed: a two-page PDF is a few
 * hundred bytes of text, and generating it keeps the repository free of a binary
 * nobody can read in a diff.
 */
import { act, createElement } from "react";
import { createRoot, type Root } from "react-dom/client";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import { Viewer } from "../src/chunks/pdf.tsx";

(globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;

const t = (key: string, values?: Record<string, string | number>): string => {
  // The real dictionary supplies a template with placeholders; a translator that
  // returned the bare key would leave `formatMessage` nothing to fill and the
  // page indicator would read `pdf.page` in every assertion.
  if (key === "pdf.page") return values === undefined ? "{current}/{total}" : `${String(values.current)}/${String(values.total)}`;
  return values === undefined ? key : `${key}:${JSON.stringify(values)}`;
};

/**
 * A minimal valid two-page PDF.
 *
 * Hand-built rather than generated by a library: the point is a document pdf.js
 * has to parse, and a real one would only make the fixture unreadable.
 * @returns the file's bytes.
 */
function twoPagePdf(): Uint8Array {
  const objects: string[] = [];
  objects[1] = "<< /Type /Catalog /Pages 2 0 R >>";
  objects[2] = "<< /Type /Pages /Kids [3 0 R 4 0 R] /Count 2 >>";
  objects[3] = "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 200 300] /Contents 5 0 R >>";
  objects[4] = "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 400 500] /Contents 6 0 R >>";
  const one = "BT 20 150 Td (Page One) Tj ET";
  const two = "BT 20 250 Td (Page Two) Tj ET";
  objects[5] = `<< /Length ${String(one.length)} >>\nstream\n${one}\nendstream`;
  objects[6] = `<< /Length ${String(two.length)} >>\nstream\n${two}\nendstream`;

  let out = "%PDF-1.4\n";
  const offsets: number[] = [];
  for (let i = 1; i < objects.length; i += 1) {
    offsets[i] = out.length;
    out += `${String(i)} 0 obj\n${objects[i] ?? ""}\nendobj\n`;
  }
  const xref = out.length;
  out += `xref\n0 ${String(objects.length)}\n0000000000 65535 f \n`;
  for (let i = 1; i < objects.length; i += 1) {
    out += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
  }
  out += `trailer\n<< /Size ${String(objects.length)} /Root 1 0 R >>\nstartxref\n${String(xref)}\n%%EOF\n`;

  const bytes = new Uint8Array(out.length);
  for (let i = 0; i < out.length; i += 1) bytes[i] = out.charCodeAt(i) & 0xff;
  return bytes;
}

describe("pdf surface", () => {
  let host: HTMLDivElement;
  let root: Root;

  beforeEach(() => {
    host = document.createElement("div");
    document.body.append(host);
    root = createRoot(host);
    // jsdom has no rasterizer. The surface asks the canvas for a 2d context and
    // hands it to pdf.js; returning a stub keeps the parse real and the paint
    // out of the way.
    HTMLCanvasElement.prototype.getContext = vi.fn(() => ({
      canvas: null,
      save: () => {},
      restore: () => {},
      transform: () => {},
      fillRect: () => {},
    })) as unknown as HTMLCanvasElement["getContext"];
  });

  afterEach(async () => {
    await act(async () => {
      root.unmount();
    });
    host.remove();
  });

  /** Mount the sidebar viewer over the fixture and let the document load. */
  async function show(): Promise<void> {
    await act(async () => {
      root.render(
        createElement(Viewer, {
          path: "docs/two-pages.pdf",
          title: "two-pages.pdf",
          scope: { sessionId: "s1" },
          customData: { bytes: twoPagePdf(), path: "docs/two-pages.pdf" },
          t,
        }),
      );
    });
    // The load is a promise chain over a real parse; a few turns is enough for
    // the document proxy to resolve.
    for (let i = 0; i < 8; i += 1) {
      await act(async () => {
        await Promise.resolve();
      });
    }
  }

  it("loads a real document and reports the page count from it", async () => {
    await show();

    const surface = host.querySelector('[data-testid="preview-more-pdf"]');
    expect(surface).not.toBeNull();
    // The count comes from the parsed document, not from anything the surface
    // was told, so this is what proves the bytes reached pdf.js.
    expect(host.textContent).toContain("1/2");
  });

  it("keeps the document and its paging when one page will not rasterize", async () => {
    // jsdom cannot rasterize, so this is the paint failure path. It must not
    // throw away a parsed document: the page count and the controls are still
    // the right answer, and the reader can still move between pages.
    await show();

    expect(host.querySelector('[data-testid="preview-more-pdf"]')).not.toBeNull();
    expect(host.querySelector('[data-testid="preview-more-pdf-paint-failed"]')).not.toBeNull();
    expect(host.querySelector('[data-testid="preview-more-pdf-failed"]')).toBeNull();
  });

  it("pages forward and back within the document", async () => {
    await show();
    const buttons = [...host.querySelectorAll("button")];
    expect(buttons).toHaveLength(2);

    // First page: back is disabled, forward is not.
    expect(buttons[0]?.disabled).toBe(true);
    expect(buttons[1]?.disabled).toBe(false);

    await act(async () => {
      buttons[1]?.dispatchEvent(new MouseEvent("click", { bubbles: true }));
    });
    expect(host.textContent).toContain("2/2");

    const after = [...host.querySelectorAll("button")];
    expect(after[1]?.disabled).toBe(true);
  });

  it("shows a readable failure for bytes that are not a PDF", async () => {
    await act(async () => {
      root.render(
        createElement(Viewer, {
          path: "docs/broken.pdf",
          title: "broken.pdf",
          scope: { sessionId: "s1" },
          customData: { bytes: new Uint8Array([1, 2, 3, 4, 5, 6, 7, 8]), path: "docs/broken.pdf" },
          t,
        }),
      );
    });
    for (let i = 0; i < 8; i += 1) {
      await act(async () => {
        await Promise.resolve();
      });
    }

    const failed = host.querySelector('[data-testid="preview-more-pdf-failed"]');
    expect(failed).not.toBeNull();
    // A translated sentence, not pdf.js's developer prose.
    expect(failed?.textContent).toContain("pdf.error.");
  });
});
