function planSync(shadow, inventory) {
  const byId = new Map(inventory.map((row) => [row.id, row]));
  const sets = [];
  const unknownKeys = [];
  for (const [id, timeoutMs] of Object.entries(shadow)) {
    const row = byId.get(id);
    if (row === void 0) {
      unknownKeys.push(id);
      continue;
    }
    if (row.effectiveTimeoutMs !== timeoutMs) sets.push({ id, timeoutMs });
  }
  const shadowIds = new Set(Object.keys(shadow));
  const unmanaged = inventory.filter((row) => row.overrideTimeoutMs !== void 0 && !shadowIds.has(row.id)).map((row) => ({ id: row.id, timeoutMs: row.overrideTimeoutMs }));
  return { sets, unmanaged, unknownKeys };
}

