#!/usr/bin/env node
/**
 * Generate the scene catalog from the installed ascii.rest package.
 *
 * The catalog is what lets the settings page offer all thirty-four scenes
 * without shipping any of them: it carries only each piece's `meta` (name,
 * note, geometry, palette), which is a few hundred bytes per scene.
 *
 * Two facts make this a build step rather than a runtime read:
 *   - The pieces are ESM modules with top-level work, so the browser cannot
 *     enumerate them without loading all of them.
 *   - `meta` is only knowable by importing the module, which needs Node.
 *
 * Usage: node scripts/generate-catalog.mjs [--check]
 *   --check  fail if the committed catalog is out of date (for CI)
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, "..");
const repoRoot = resolve(packageRoot, "../..");
const OUT = join(packageRoot, "src", "catalog.generated.ts");

const require = createRequire(join(packageRoot, "package.json"));

/** Locate the installed ascii.rest package without depending on its exports map. */
function locatePackage() {
  // `exports` does not publish `./package.json`, so resolve the entry point and climb.
  const entry = require.resolve("ascii.rest");
  let dir = dirname(entry);
  for (let i = 0; i < 8; i += 1) {
    const candidate = join(dir, "package.json");
    if (existsSync(candidate)) {
      const pkg = JSON.parse(readFileSync(candidate, "utf8"));
      if (pkg.name === "ascii.rest") return { dir, pkg };
    }
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  throw new Error("catalog: could not locate the installed ascii.rest package");
}

/** Every file name under dist/pieces, without the extension. */
function pieceNames(pkgDir) {
  const piecesDir = join(pkgDir, "dist", "pieces");
  const names = [];
  for (const entry of readdirNames(piecesDir)) {
    if (!entry.endsWith(".js")) continue;
    if (entry === "index.js") continue;
    names.push(entry.slice(0, -3));
  }
  return names.sort();
}

function readdirNames(dir) {
  // eslint-disable-next-line n/no-sync -- a build script has nowhere else to be
  return require("node:fs").readdirSync(dir);
}

/**
 * Import one piece and keep it only if it declares itself a scene.
 *
 * A piece module is `export const meta` plus `export default`. Importing it has
 * the side effects its author wrote, which is exactly why this runs in Node at
 * build time and never in the browser.
 */
async function readScene(pkgDir, name) {
  const file = pathToFileURL(join(pkgDir, "dist", "pieces", `${name}.js`)).href;
  const mod = await import(file);
  const meta = mod.meta;
  if (!meta || meta.category !== "scenes") return null;
  return {
    id: name,
    name: meta.name,
    note: meta.note,
    cols: meta.cols,
    rows: meta.rows,
    cell: meta.cell ?? 2,
    fps: meta.fps,
    ground: meta.ground,
    palette: meta.palette,
    still: meta.still ?? 0,
    ...(meta.loop === undefined ? {} : { loop: meta.loop }),
  };
}

function render(scenes, pkg, commit) {
  const header = [
    "/*",
    " * Generated by scripts/generate-catalog.mjs. Do not edit by hand.",
    " *",
    ` * Source:  ${pkg.repository?.url ?? "ascii.rest"} @ ${commit}`,
    ` * Version: ${pkg.version}`,
    ` * Scenes:  ${scenes.length}`,
    " */",
    "",
    'import type { CatalogSource, SceneEntry } from "./types.ts";',
    "",
    `export const CATALOG_SOURCE: CatalogSource = ${JSON.stringify(
      {
        repository: "bas3line/ascii",
        commit,
        packageVersion: pkg.version,
      },
      null,
      2,
    )};`,
    "",
    "/** Every piece the library declares as a scene, in file-name order. */",
    `export const SCENES: readonly SceneEntry[] = ${JSON.stringify(scenes, null, 2)};`,
    "",
  ];
  return header.join("\n");
}

/** The commit the dependency is pinned to, read from the workspace manifest. */
function pinnedCommit() {
  const manifest = JSON.parse(readFileSync(join(packageRoot, "package.json"), "utf8"));
  const spec = manifest.dependencies?.["ascii.rest"] ?? "";
  const match = /#([0-9a-f]{40})$/.exec(spec);
  return match?.[1] ?? "unknown";
}

async function main() {
  const { dir: pkgDir, pkg } = locatePackage();
  const names = pieceNames(pkgDir);

  const scenes = [];
  for (const name of names) {
    const scene = await readScene(pkgDir, name);
    if (scene !== null) scenes.push(scene);
  }
  if (scenes.length === 0) throw new Error("catalog: the installed package declares no scenes");

  const output = render(scenes, pkg, pinnedCommit());

  if (process.argv.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (current !== output) {
      console.error("catalog: src/catalog.generated.ts is out of date; run `pnpm build`");
      process.exit(1);
    }
    console.log(`catalog: up to date (${scenes.length} scenes)`);
    return;
  }

  writeFileSync(OUT, output);
  const bytes = Buffer.byteLength(output);
  console.log(`catalog: wrote ${scenes.length} scenes to src/catalog.generated.ts (${bytes} bytes)`);
  console.log(`catalog: first is ${scenes[0].id}, last is ${scenes.at(-1).id}`);

  // The catalog is committed, so the repo root must count it as source.
  if (!existsSync(join(repoRoot, "package.json"))) console.warn("catalog: unexpected repo layout");
}

await main();
