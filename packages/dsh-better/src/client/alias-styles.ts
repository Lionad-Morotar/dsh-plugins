/**
 * Insert the page stylesheet once.
 * @param doc - document to style.
 * @returns the symmetric teardown.
 */
export function insertAliasPageStyles(doc: Document): () => void {
  const selector = `style[data-plugin-css=${JSON.stringify(ALIAS_PAGE_STYLE_TAG)}]`;
  if (doc.querySelector(selector) !== null) return () => undefined;
  const tag = doc.createElement("style");
  tag.dataset.plugin = "dsh-better";
  tag.dataset.pluginCss = ALIAS_PAGE_STYLE_TAG;
  tag.textContent = ALIAS_PAGE_CSS;
  doc.head.append(tag);
  return () => tag.remove();
}
